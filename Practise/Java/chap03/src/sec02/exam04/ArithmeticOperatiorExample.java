public class ArithmeticOperatiorExample {

	public static void main(String[] args) {
		int v1 = 5;
		int v2 = 2;
		
		int rseult1 = v1 + v2;
		System.out.println("rseult1=" + rseult1);
		
		int rseult2 = v1 - v2;
		System.out.println("rseult2=" + rseult2);
		
		int rseult3 = v1 * v2;
		System.out.println("rseult3=" + rseult3);
		
		int rseult4 = v1 / v2;
		System.out.println("rseult4=" + rseult4);
		
		int rseult5 = v1 % v2;
		System.out.println("rseult5=" + rseult5);
		
		double result6 = (double) v1 / v2;
		System.out.println("result6" + result6);
		
	}
	
}
